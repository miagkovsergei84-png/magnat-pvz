globalThis.PptCharacterAssets = (() => {
  const paths=globalThis.PptCharacterAssetPaths;
  const entries=new Map(paths.entries.map(entry=>[entry.logical,entry]));
  const images=new Map(),states=new WeakMap();
  function image(logical){
    if(images.has(logical))return images.get(logical);
    const entry=entries.get(logical);
    if(!entry)throw new Error('Unregistered character asset: '+logical);
    const result=new Image(),state={logical,ready:false,fallback:false,failed:false};
    images.set(logical,result);states.set(result,state);
    const fallback=paths.format==='webp'?entry.fallback:null;
    function fail(){
      state.ready=false;
      if(state.failed)return;
      if(fallback&&!state.fallback){state.fallback=true;result.src=fallback;}
      else state.failed=true;
    }
    result.onerror=fail;
    result.onload=()=>{
      if(state.failed)return;
      const expected=state.fallback?entries.get(fallback):entry;
      if(!expected||result.naturalWidth!==expected.width||result.naturalHeight!==expected.height){fail();return;}
      state.ready=true;
    };
    // No PNG preload: an approved static fallback is requested only on failure.
    // Atlas/sheet entries deliberately have no PNG fallback. Their renderer
    // chooses a static sprite instead of putting an idle image into atlas crops.
    result.src=paths.format==='png'?entry.logical:entry.preferred;
    return result;
  }
  const ready=image=>!!states.get(image)?.ready&&image.complete&&image.naturalWidth>0;
  const logical=image=>states.get(image)?.logical;
  return {image,ready,logical,paths};
})();
